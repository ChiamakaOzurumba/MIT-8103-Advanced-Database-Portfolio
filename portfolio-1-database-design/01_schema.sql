--   asset_copy, licence_holder, licence, loan, preservation_event)
-- Features: enums, CHECK, UNIQUE, partial unique indexes, BEFORE trigger
\set ON_ERROR_STOP on

BEGIN;
DROP SCHEMA IF EXISTS public CASCADE;
CREATE SCHEMA public;
CREATE EXTENSION IF NOT EXISTS pgcrypto;
CREATE EXTENSION IF NOT EXISTS btree_gist;

-- ===== Enums =====
CREATE TYPE asset_status   AS ENUM ('DRAFT','CATALOGUED','ARCHIVED','DEPRECATED');
CREATE TYPE asset_medium   AS ENUM ('AUDIO','VIDEO','PHOTO','DOCUMENT');
CREATE TYPE copy_kind      AS ENUM ('PHYSICAL','DIGITAL');
CREATE TYPE contributor_role AS ENUM ('CREATOR','DIRECTOR','PRODUCER','PERFORMER','EDITOR','CINEMATOGRAPHER');
CREATE TYPE creator_type   AS ENUM ('PERSON','ORGANISATION');
CREATE TYPE licence_type   AS ENUM ('EXCLUSIVE','NON_EXCLUSIVE','CREATIVE_COMMONS','PUBLIC_DOMAIN');
CREATE TYPE loan_status    AS ENUM ('REQUESTED','APPROVED','ACTIVE','RETURNED','OVERDUE','REJECTED');
CREATE TYPE preservation_action AS ENUM ('INSPECTION','MIGRATION','RESTORATION','REPAIR','DISPOSAL');
CREATE TYPE user_role      AS ENUM ('ARCHIVIST','LIBRARIAN','ADMIN','RESEARCHER');

-- ===== role =====
CREATE TABLE role (
    role_id     INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        user_role NOT NULL UNIQUE,
    description TEXT
);

-- ===== users (passwords never in plain text) =====
CREATE TABLE users (
    user_id        INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    role_id        INTEGER NOT NULL REFERENCES role(role_id),
    full_name      TEXT    NOT NULL CHECK (full_name <> ''),
    email          TEXT    NOT NULL CHECK (email ~* '^[^@ ]+@[^@ ]+\.[^@ ]+$'),
    password_hash  TEXT    NOT NULL CHECK (length(password_hash) >= 20),
    is_active      BOOLEAN NOT NULL DEFAULT true,
    created_at     TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- ===== archive_collection (self-referencing hierarchy) =====
CREATE TABLE archive_collection (
    collection_id        INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    parent_collection_id INTEGER REFERENCES archive_collection(collection_id),
    name                 TEXT NOT NULL CHECK (name <> ''),
    code                 TEXT NOT NULL UNIQUE,
    is_active            BOOLEAN NOT NULL DEFAULT true,
    created_at           TIMESTAMPTZ NOT NULL DEFAULT now(),
    CHECK (code ~ '^[A-Z0-9_-]+$')
);

-- ===== creator (persons or organisations) =====
CREATE TABLE creator (
    creator_id    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    creator_type  creator_type NOT NULL,
    full_name     TEXT NOT NULL CHECK (full_name <> ''),
    nationality   TEXT,
    email         TEXT CHECK (email IS NULL OR email ~* '^[^@ ]+@[^@ ]+\.[^@ ]+$')
);

-- ===== asset_format =====
CREATE TABLE asset_format (
    format_id     INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          TEXT NOT NULL UNIQUE CHECK (name <> ''),
    medium        asset_medium NOT NULL,
    is_obsolete   BOOLEAN NOT NULL DEFAULT false
);

-- ===== media_asset (the catalogue record) =====
CREATE TABLE media_asset (
    asset_id       INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    collection_id  INTEGER NOT NULL REFERENCES archive_collection(collection_id),
    format_id      INTEGER NOT NULL REFERENCES asset_format(format_id),
    title          TEXT NOT NULL CHECK (title <> ''),
    medium         asset_medium NOT NULL,
    status         asset_status NOT NULL DEFAULT 'DRAFT',
    duration_sec   INTEGER CHECK (duration_sec IS NULL OR duration_sec > 0),
    checksum       TEXT,
    acquired_at    DATE NOT NULL DEFAULT CURRENT_DATE,
    created_at     TIMESTAMPTZ NOT NULL DEFAULT now()
    -- medium/format consistency is enforced by trg_asset_format_medium below
);

-- ===== asset_contributor (junction with role) =====
CREATE TABLE asset_contributor (
    asset_id     INTEGER NOT NULL REFERENCES media_asset(asset_id) ON DELETE CASCADE,
    creator_id   INTEGER NOT NULL REFERENCES creator(creator_id),
    role         contributor_role NOT NULL,
    PRIMARY KEY (asset_id, creator_id, role)
);

-- ===== subject_tag =====
CREATE TABLE subject_tag (
    tag_id   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name     TEXT NOT NULL CHECK (name <> '')
);

-- ===== asset_tag (junction) =====
CREATE TABLE asset_tag (
    asset_id INTEGER NOT NULL REFERENCES media_asset(asset_id) ON DELETE CASCADE,
    tag_id   INTEGER NOT NULL REFERENCES subject_tag(tag_id) ON DELETE CASCADE,
    PRIMARY KEY (asset_id, tag_id)
);

-- ===== storage_location =====
CREATE TABLE storage_location (
    location_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code        TEXT NOT NULL UNIQUE CHECK (code ~ '^[A-Z0-9_-]+$'),
    site        TEXT NOT NULL CHECK (site <> ''),
    city        TEXT NOT NULL DEFAULT 'Lagos',
    capacity    INTEGER NOT NULL DEFAULT 1000 CHECK (capacity > 0)
);

-- ===== asset_copy (physical or digital copy of an asset) =====
CREATE TABLE asset_copy (
    copy_id      INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    asset_id     INTEGER NOT NULL REFERENCES media_asset(asset_id) ON DELETE CASCADE,
    location_id  INTEGER NOT NULL REFERENCES storage_location(location_id),
    kind         copy_kind NOT NULL,
    barcode      TEXT NOT NULL UNIQUE CHECK (barcode ~ '^[A-Z0-9-]+$'),
    is_available BOOLEAN NOT NULL DEFAULT true,
    created_at   TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- ===== licence_holder =====
CREATE TABLE licence_holder (
    holder_id  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name       TEXT NOT NULL UNIQUE CHECK (name <> ''),
    country    TEXT NOT NULL DEFAULT 'Nigeria',
    contact_email TEXT CHECK (contact_email IS NULL OR contact_email ~* '^[^@ ]+@[^@ ]+\.[^@ ]+$')
);

-- ===== licence =====
CREATE TABLE licence (
    licence_id   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    asset_id     INTEGER NOT NULL REFERENCES media_asset(asset_id) ON DELETE CASCADE,
    holder_id    INTEGER NOT NULL REFERENCES licence_holder(holder_id),
    licence_type licence_type NOT NULL,
    start_date   DATE NOT NULL,
    end_date     DATE NOT NULL,
    fee_naira    NUMERIC(12,2) NOT NULL DEFAULT 0 CHECK (fee_naira >= 0),
    CHECK (end_date >= start_date)
);

-- ===== loan (access request) =====
CREATE TABLE loan (
    loan_id       INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    asset_copy_id INTEGER NOT NULL REFERENCES asset_copy(copy_id) ON DELETE CASCADE,
    user_id       INTEGER NOT NULL REFERENCES users(user_id),
    status        loan_status NOT NULL DEFAULT 'REQUESTED',
    start_at      TIMESTAMPTZ NOT NULL,
    end_at        TIMESTAMPTZ NOT NULL,
    requested_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    CHECK (end_at > start_at)
);

-- ===== preservation_event (the bulk-loaded fact table) =====
CREATE TABLE preservation_event (
    event_id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    asset_id   INTEGER NOT NULL REFERENCES media_asset(asset_id) ON DELETE CASCADE,
    action     preservation_action NOT NULL,
    event_date DATE NOT NULL,
    operator   TEXT NOT NULL CHECK (operator <> ''),
    outcome    TEXT NOT NULL CHECK (outcome <> ''),
    notes      TEXT
);

-- ===== Trigger: asset cannot be ARCHIVED without a checksum =====
CREATE OR REPLACE FUNCTION enforce_checksum_for_archived()
RETURNS TRIGGER LANGUAGE plpgsql AS $$
BEGIN
    IF NEW.status = 'ARCHIVED' AND (NEW.checksum IS NULL OR NEW.checksum = '') THEN
        RAISE EXCEPTION 'Asset % cannot be marked ARCHIVED without a checksum', NEW.asset_id;
    END IF;
    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_asset_checksum
BEFORE INSERT OR UPDATE OF status, checksum ON media_asset
FOR EACH ROW EXECUTE FUNCTION enforce_checksum_for_archived();

-- ===== Trigger: keep asset_copy.is_available false while loan ACTIVE =====
CREATE OR REPLACE FUNCTION sync_copy_availability()
RETURNS TRIGGER LANGUAGE plpgsql AS $$
BEGIN
    IF NEW.status IN ('APPROVED','ACTIVE') THEN
        UPDATE asset_copy SET is_available = false WHERE copy_id = NEW.asset_copy_id;
    ELSIF NEW.status IN ('RETURNED','REJECTED') THEN
        UPDATE asset_copy SET is_available = true  WHERE copy_id = NEW.asset_copy_id;
    END IF;
    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_loan_sync_copy
AFTER INSERT OR UPDATE OF status ON loan
FOR EACH ROW EXECUTE FUNCTION sync_copy_availability();

-- ===== Trigger: asset.medium must match its format.medium =====
CREATE OR REPLACE FUNCTION enforce_asset_format_medium()
RETURNS TRIGGER LANGUAGE plpgsql AS $$
DECLARE
    fmt_medium asset_medium;
BEGIN
    SELECT medium INTO fmt_medium FROM asset_format WHERE format_id = NEW.format_id;
    IF fmt_medium IS NULL THEN
        RAISE EXCEPTION 'Format % not found for asset %', NEW.format_id, NEW.asset_id;
    END IF;
    IF NEW.medium <> fmt_medium THEN
        RAISE EXCEPTION 'Asset % medium % does not match format % medium %',
            NEW.asset_id, NEW.medium, NEW.format_id, fmt_medium;
    END IF;
    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_asset_format_medium
BEFORE INSERT OR UPDATE OF format_id, medium ON media_asset
FOR EACH ROW EXECUTE FUNCTION enforce_asset_format_medium();

COMMIT;
